"""Исключения приложения. Интерфейс перехватывает AppError и показывает понятное сообщение."""


class AppError(Exception):
    """Базовая ошибка приложения с текстом, пригодным для показа пользователю."""


class ConfigError(AppError):
    """Файл настроек отсутствует или заполнен неверно."""


class DatabaseError(AppError):
    """Ошибка при работе с базой данных."""


class DatabaseConnectionError(DatabaseError):
    """Не удалось подключиться к базе данных."""


class OrderError(AppError):
    """Нарушено бизнес-правило при работе с заказом (например, не хватает товара)."""
