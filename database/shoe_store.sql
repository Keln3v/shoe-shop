DROP TABLE IF EXISTS order_items, orders, stock_items, sizes, products,
                     manufacturers, subcategories, categories, users, roles CASCADE;

CREATE TABLE roles (
    role_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE users (
    user_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    last_name   VARCHAR(50) NOT NULL,
    first_name  VARCHAR(50) NOT NULL,
    patronymic  VARCHAR(50),
    login       VARCHAR(50) NOT NULL UNIQUE,
    role_id     INTEGER NOT NULL REFERENCES roles (role_id) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE categories (
    category_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE subcategories (
    subcategory_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subcategory_name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE manufacturers (
    manufacturer_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manufacturer_name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE products (
    product_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id     INTEGER NOT NULL REFERENCES categories (category_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    subcategory_id  INTEGER NOT NULL REFERENCES subcategories (subcategory_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    manufacturer_id INTEGER NOT NULL REFERENCES manufacturers (manufacturer_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    product_name    VARCHAR(150) NOT NULL,
    description     TEXT NOT NULL,
    composition     TEXT NOT NULL,
    price           NUMERIC(10, 2) NOT NULL CHECK (price > 0),
    image_file      VARCHAR(100),
    UNIQUE (product_name, manufacturer_id)
);

CREATE TABLE sizes (
    size_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    size_value NUMERIC(3, 1) NOT NULL UNIQUE
);

-- Товарная позиция: сочетание модели и размера с доступным количеством
CREATE TABLE stock_items (
    stock_item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id    INTEGER NOT NULL REFERENCES products (product_id) ON UPDATE CASCADE ON DELETE CASCADE,
    size_id       INTEGER NOT NULL REFERENCES sizes (size_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    quantity      INTEGER NOT NULL CHECK (quantity >= 0),
    UNIQUE (product_id, size_id)
);

CREATE TABLE orders (
    order_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_date DATE NOT NULL,
    user_id    INTEGER NOT NULL REFERENCES users (user_id) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE order_items (
    order_item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      INTEGER NOT NULL REFERENCES orders (order_id) ON UPDATE CASCADE ON DELETE CASCADE,
    stock_item_id INTEGER NOT NULL REFERENCES stock_items (stock_item_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    quantity      INTEGER NOT NULL CHECK (quantity > 0),
    unit_price    NUMERIC(10, 2) NOT NULL CHECK (unit_price > 0),
    UNIQUE (order_id, stock_item_id)
);

CREATE INDEX idx_stock_items_product ON stock_items (product_id);
CREATE INDEX idx_orders_date ON orders (order_date);
CREATE INDEX idx_order_items_stock ON order_items (stock_item_id);

